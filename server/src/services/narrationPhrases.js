export function shufflePhrases(phrases) {
  const shuffled = [...phrases];
  for (let index = shuffled.length - 1; index > 0; index -= 1) {
    const randomIndex = Math.floor(Math.random() * (index + 1));
    [shuffled[index], shuffled[randomIndex]] = [shuffled[randomIndex], shuffled[index]];
  }
  return shuffled;
}

export function createPhraseSchedule(questionCount, random = Math.random) {
  const questionIntroIndices = new Set();
  const solutionIntroIndices = new Set();
  let completedQuestions = 2 + Math.floor(random() * 4);

  while (completedQuestions <= questionCount) {
    const canIntroduceNextQuestion = completedQuestions < questionCount;
    if (canIntroduceNextQuestion && random() < 0.5) {
      questionIntroIndices.add(completedQuestions);
    } else {
      solutionIntroIndices.add(completedQuestions - 1);
    }
    completedQuestions += 2 + Math.floor(random() * 4);
  }

  return { questionIntroIndices, solutionIntroIndices };
}